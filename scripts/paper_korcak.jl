# Table I (draft/tables/korcak.tex) and Fig. 3 (draft/figures/korcak.pdf) of the
# paper: vertex scaling α, boundary-pixel exponent d_b, single-grid Korčák
# dimension 2K and Wada averages; relaxed Newton family against Saupe's d_F.
# Also prints the other numbers quoted in the Results section.
include(joinpath(@__DIR__, "paper_common.jl"))

# Reuse the Newton sweep of fig_newton.jl when it is available.
function load_or_analyze(name, get, Ns)
    file = datadir("paper_results", "$(name).jld2")
    if isfile(file)
        r = wload(file)
        r["Ns"] == collect(Ns) && return r
    end
    analyze_system(name, get, Ns)
end

# (name, table label, getter, analysed grids, smallest grid of the fits)
systems = [
    ("newton",   "Newton \$z^3-1\$",   get_basins_newton,
     [50, 75, 100, 150, 200, 300, 400, 500, 700, 1000, 1400, 2000], 200),
    ("magnetic", "Magnetic pendulum",  get_basins_magnetic,
     [100, 150, 200, 300, 400, 500], 100),
    ("feudel",   "Feudel map",         get_basins_feudel,
     [100, 150, 200, 300, 400, 500], 100),
    ("duffing",  "Duffing oscillator", N -> get_basins_duffing(DUFFING_F, N),
     [100, 150, 200, 300, 400, 500, 700, 1000], 100),
]

rows = map(systems) do (name, label, get, Ns, Nmin)
    e = exponents(load_or_analyze(name, get, Ns); Nmin)
    s = last(e.stats); Nf = last(e.Ns)
    wr = extrema(x.wada_frac for x in e.stats)
    @printf("%-9s N=%d–%d  α=%.3f (R²=%.4f)  d_b=%.3f  2K=%.3f  Wada∈[%.3f, %.3f]  w̄=%.3f (range %.3f–%.3f)  <k>∈[%.2f, %.2f]  kmax~|V|^%.2f  Nb/N²=%.3f\n",
            name, first(e.Ns), Nf, e.α, e.R2, e.d_b, s.twoK, wr..., s.w,
            extrema(x.w for x in e.stats)..., extrema(x.k for x in e.stats)..., e.x_kmax, s.nb / Nf^2)
    [label, string(s.NA), fmt(e.d_b), fmt(e.α), fmt(s.twoK), @sprintf("%.2f--%.2f", wr...), fmt(s.w; d = 2)]
end

body = join(["    " * join(r, " & ") * " \\\\" for r in rows], "\n")
write(joinpath(TABDIR, "korcak.tex"), """
% Generated by AnalysisBasinsNets/scripts/paper_korcak.jl -- do not edit by hand.
\\begin{table*}[t]
  \\centering
  \\small
  \\caption{Korčák analysis of the BAG. \$d_b\$ and \$\\alpha\$: exponents of the number of boundary
    pixels and of vertices with the resolution. \$2K\$: Korčák
    dimension fitted on the finest grid. Wada: range over \$N\$ of the fraction of boundary
    components adjacent to all other basins; \$\\bar w\$: mean number of other basins adjacent to
    a boundary component, on the finest grid.}
  \\label{tab:korcak}
  \\begin{tabular}{lcccccc}
    \\toprule
    System & \$N_A\$ & \$d_b\$ & \$\\alpha\$ & \$2K\$ & Wada & \$\\bar w\$ \\\\
    \\midrule
$body
    \\bottomrule
  \\end{tabular}
\\end{table*}
""")
println("wrote ", joinpath(TABDIR, "korcak.tex"))

# Relaxed Newton family: N = 250…2000 in steps of √2.
const SAUPE_NS = [250, 354, 500, 707, 1000, 1414, 2000]
hs = sort(collect(keys(SAUPE_DF)))
dF = [SAUPE_DF[h] for h in hs]
saupe = map(hs) do h
    exponents(load_or_analyze("saupe_h=$(h)", N -> get_basins_saupe(h, N), SAUPE_NS))
end
for (h, d, e) in zip(hs, dF, saupe)
    s = last(e.stats)
    @printf("h=%.1f  d_F=%.3f  d_b=%.3f  α=%.3f  2K=%.3f  w̄=%.3f  |d_b-d_F|=%.3f  |α-d_F|=%.3f  |2K-α|=%.3f\n",
            h, d, e.d_b, e.α, s.twoK, s.w, abs(e.d_b - d), abs(e.α - d), abs(s.twoK - e.α))
end
twoK = [last(e.stats).twoK for e in saupe]; α = [e.α for e in saupe]
@printf("Saupe: max|d_b-d_F| = %.3f;  max|α-d_F| (h≥0.5) = %.3f;  max|2K-α| (h≥0.7) = %.3f;  w̄ ∈ [%.3f, %.3f]\n",
        maximum(abs.([e.d_b for e in saupe] .- dF)), maximum(abs.(α .- dF)[hs .≥ 0.5]),
        maximum(abs.(twoK .- α)[hs .≥ 0.7]), extrema(last(e.stats).w for e in saupe)...)

fig = Figure(size = (300, 280))
ax = Axis(fig[1, 1]; xlabel = L"d_F\ \mathrm{(Saupe)}", ylabel = "exponent", aspect = 1)
lines!(ax, [1.2, 1.72], [1.2, 1.72]; color = :gray, linestyle = :dash)
scatter!(ax, dF, [e.d_b for e in saupe]; label = L"d_b", marker = :rect)
scatter!(ax, dF, α; label = L"\alpha")
scatter!(ax, dF, twoK; label = L"2K", marker = :utriangle)
axislegend(ax; position = :lt, framevisible = false)
save(joinpath(FIGDIR, "korcak.pdf"), fig; pt_per_unit = 1)
println("wrote ", joinpath(FIGDIR, "korcak.pdf"))
