fmt(x; d = 3) = (x isa Real && isfinite(x)) ? @sprintf("%.*f", d, x) : "---"
fmte(x) = (x isa Real && isfinite(x) && x > 0) ? @sprintf("%.1e", x) : "---"

save_patch(name, res) = wsave(datadir("patch_results", "$(name).jld2"), Dict("res" => res))
load_patch(name) = wload(datadir("patch_results", "$(name).jld2"))["res"]

"""
    write_table(file, caption, label, header, rows; colspec, wide = true)

Write a booktabs table to draft/tables/`file`; `rows` are vectors of strings.
"""
function write_table(file, caption, label, header, rows; colspec = "l" * "c"^(length(header) - 1),
                     wide = true, note = "")
    env = wide ? "table*" : "table"
    # wide tables are scaled to the text width
    body = join(["    " * join(r, " & ") * " \\\\" for r in rows], "\n")
    tex = """
    % Generated by AnalysisBasinsNets/scripts/$(basename(PROGRAM_FILE == "" ? "patch" : PROGRAM_FILE)) -- do not edit by hand.
    \\begin{$env}[t]
      \\centering
      \\small
      \\caption{$caption}
      \\label{$label}
      $(wide ? "\\resizebox{\\textwidth}{!}{%\n  " : "")\\begin{tabular}{$colspec}
        \\toprule
        $(join(header, " & ")) \\\\
        \\midrule
    $body
        \\bottomrule
      \\end{tabular}$(wide ? "}" : "")$(isempty(note) ? "" : "\n  \\par\\smallskip\\footnotesize $note")
    \\end{$env}
    """
    write(joinpath(TABDIR, file), tex)
    println("wrote ", joinpath(TABDIR, file))
end

# Print and store the resolution metrics of one case.
function run_case(name, get, Ns)
    t = @elapsed r = resolution_metrics(get, Ns)
    m = r.last
    @printf("%-16s |V|=%7d α=%.3f d_b=%.3f 2K=%.3f β=%.3f p=%.3f γ=%.3f τ=%.2f α/2β=%.2f tri/V=%.2f a*=%.1e|%.1e (%.0fs)\n",
            name, m.nv, r.α, r.d_b, m.twoK, m.β, m.p, m.γ, m.τ, r.α / (2m.β), m.tri_per_v,
            m.a_lr, m.a_tb, t)
    flush(stdout)
    save_patch(name, r)
    return r
end
