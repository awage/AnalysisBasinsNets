# Table 1 and the α vs d_f comparison figure, from the results saved by the
# fig_*.jl scripts (run make_paper.jl to produce everything).
include(joinpath(@__DIR__, "paper_common.jl"))

# (result name, table label, expected d_f or "")
rows = [
    ("sierpinski_triangle", "Sierpi\\'nski triangle", "1.585 (exact)"),
    ("sierpinski_carpet",   "Sierpi\\'nski carpet",   "1.893 (exact)"),
    ("newton",              "Newton \$z^3-1\$",       ""),
    ("duffing",             "Duffing oscillator",     ""),
    ("magnetic",            "Magnetic pendulum",      ""),
    ("feudel",              "Feudel map",             "\$\\sim\$1.93~\\cite{feudel1998}"),
]

fmt(x; d = 3) = isnan(x) ? "---" : @sprintf("%.*f", d, x)

lines = String[]
for (name, label, expected) in rows
    isfile(datadir("paper_results", "$(name).jld2")) || (@warn "missing $name"; continue)
    r = load_results(name)
    s = r["stats"][end]
    wmin, wmax = extrema(x.wada_frac for x in r["stats"])
    wada = s.NA ≥ 3 ? fmt(s.wada_frac; d = 2) : "---"
    merge = s.NA ≥ 3 ? @sprintf("%.3f", r["wada_merge"]) : "---"
    α = isnan(r["R2"]) ? "const." : fmt(r["alpha"])   # |V| independent of N
    if haskey(r, "d_grebogi")   # grid-free uncertainty exponent
        expected = @sprintf("%.2f (unc.\\ exp.)", r["d_grebogi"])
    end
    push!(lines, join([label, string(s.NA), α, fmt(r["R2"]), fmt(s.k; d = 2),
                       wada, merge, fmt(r["d_box"]), expected], " & ") * " \\\\")
    @printf("%-20s NA=%d α=%.3f R²=%.4f <k>=%.2f wada=%.3f (range %.3f–%.3f over N) w=%.2f d=%.3f\n",
            name, s.NA, r["alpha"], r["R2"], s.k, s.wada_frac, wmin, wmax, s.w, r["d_box"])
end

table = """
% Generated by AnalysisBasinsNets/scripts/table_summary.jl -- do not edit by hand.
\\begin{table*}[t]
  \\centering
  \\small
  \\caption{Basin adjacency graph metrics across all systems. \$N_A\$ is the number of
  attractors; \$\\alpha\$ is the exponent of the vertex scaling \$|V|\\sim N^{\\alpha}\$ and \$d_b\$ the
  exponent of the number of boundary pixels, \$N_b\\sim N^{d_b}\$ (box-counting dimension of the
  boundary, uncertainty exponent \$\\alpha_u=2-d_b\$~\\cite{mcdonald1985}), both fitted over the same
  grids with \$N\\geq 100\$ (all levels for the Sierpi\\'nski fractals). \$\\langle k\\rangle\$, the Wada fraction and the merging-method Wada
  test~\\cite{daza2018} (\$0\$ for Wada basins) are evaluated at the finest resolution. The last
  column gives the dimension obtained independently of the grid, when available.}
  \\label{tab:summary}
  \\begin{tabular}{lcccccccc}
    \\toprule
    System & \$N_A\$ & \$\\alpha\$ & \$R^2\$ & \$\\langle k\\rangle\$ & Wada frac. & Merge test & \$d_b\$ & \$d_f\$ (independent) \\\\
    \\midrule
$(join("    " .* lines, "\n"))
    \\bottomrule
  \\end{tabular}
\\end{table*}
"""
write(joinpath(TABDIR, "table1.tex"), table)
println("wrote ", joinpath(TABDIR, "table1.tex"))

# α versus the box-counting dimension of the boundary
fig = Figure(size = (440, 280))
ax = Axis(fig[1, 1]; aspect = 1, xlabel = L"d_f\ \mathrm{(box\ counting)}", ylabel = L"\alpha\ \mathrm{(BAG)}",
          title = "BAG exponent vs boundary dimension")
lines!(ax, [0.8, 2], [0.8, 2]; color = :gray, linestyle = :dash)
for (k, (name, label, _)) in enumerate(rows)
    isfile(datadir("paper_results", "$(name).jld2")) || continue
    r = load_results(name)
    isnan(r["R2"]) && continue   # no scaling (|V| independent of N)
    scatter!(ax, [r["d_box"]], [r["alpha"]]; color = Makie.wong_colors()[mod1(k, 7)],
             marker = k > 7 ? :diamond : :circle,
             label = replace(label, "\\'n" => "ń", "\$" => "", "z^3-1" => "z³−1"))
end
limits!(ax, 0.8, 2.0, 0.8, 2.0)
Legend(fig[1, 2], ax; framevisible = false, labelsize = 9)
save(joinpath(FIGDIR, "alpha_vs_df.pdf"), fig; pt_per_unit = 1)
